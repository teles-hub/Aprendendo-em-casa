idade = 18
nome = "Cauê"
print(f"Meu nome é {nome} e eu tenho {idade} ano(s) de idade")
#no python vc pode declarar varias variaveis na mesma linha
idade, nome = (18, "Cauê")
print(f"Meu nome é {nome} e eu tenho {idade} ano(s) de idade")

#Se uma variavel for escrita totalmente em maiusculo ele se torna uma constante (isso é uma convenção dácomunidade)
IDADE = 13
NOME = "Miguel"
print(f"Meu nome é {NOME} e eu tenho {IDADE} ano(s) de idade")

